// Register data from Waveshare's 01_gfx_helloworld demo for this panel.
// The ST7789-compatible drawing interface alone is not sufficient to boot it.
inline void initialize_touch_panel(Arduino_DataBus *bus) {
  struct Register {
    uint8_t command;
    uint8_t length;
    uint8_t data[32];
  };
  static const Register registers[] = {
      {0xDF, 2, {0x98, 0x53}},
      {0xB2, 1, {0x23}},
      {0xB7, 4, {0x00, 0x47, 0x00, 0x6F}},
      {0xBB, 6, {0x1C, 0x1A, 0x55, 0x73, 0x63, 0xF0}},
      {0xC0, 2, {0x44, 0xA4}},
      {0xC1, 1, {0x16}},
      {0xC3, 8, {0x7D, 0x07, 0x14, 0x06, 0xCF, 0x71, 0x72, 0x77}},
      {0xC4, 12, {0x00, 0x00, 0xA0, 0x79, 0x0B, 0x0A,
                   0x16, 0x79, 0x0B, 0x0A, 0x16, 0x82}},
      {0xC8, 32, {0x3F, 0x32, 0x29, 0x29, 0x27, 0x2B, 0x27, 0x28,
                   0x28, 0x26, 0x25, 0x17, 0x12, 0x0D, 0x04, 0x00,
                   0x3F, 0x32, 0x29, 0x29, 0x27, 0x2B, 0x27, 0x28,
                   0x28, 0x26, 0x25, 0x17, 0x12, 0x0D, 0x04, 0x00}},
      {0xD0, 5, {0x04, 0x06, 0x6B, 0x0F, 0x00}},
      {0xD7, 2, {0x00, 0x30}},
      {0xE6, 1, {0x14}},
      {0xDE, 1, {0x01}},
      {0xB7, 5, {0x03, 0x13, 0xEF, 0x35, 0x35}},
      {0xC1, 3, {0x14, 0x15, 0xC0}},
      {0xC2, 2, {0x06, 0x3A}},
      {0xC4, 2, {0x72, 0x12}},
      {0xBE, 1, {0x00}},
      {0xDE, 1, {0x02}},
      {0xE5, 3, {0x00, 0x02, 0x00}},
      {0xE5, 3, {0x01, 0x02, 0x00}},
      {0xDE, 1, {0x00}},
      {0x35, 1, {0x00}},
      {0x3A, 1, {0x05}},
      {0x2A, 4, {0x00, 0x22, 0x00, 0xCD}},
      {0x2B, 4, {0x00, 0x00, 0x01, 0x3F}},
      {0xDE, 1, {0x02}},
      {0xE5, 3, {0x00, 0x02, 0x00}},
      {0xDE, 1, {0x00}},
      {0x36, 1, {0x00}},
      {0x21, 0, {}},
  };
  bus->beginWrite();
  bus->writeCommand(0x11);
  bus->endWrite();
  delay(120);
  bus->beginWrite();
  for (const auto &reg : registers) {
    bus->writeCommand(reg.command);
    for (uint8_t i = 0; i < reg.length; ++i) {
      bus->write(reg.data[i]);
    }
  }
  bus->endWrite();
  delay(10);
  bus->beginWrite();
  bus->writeCommand(0x29);
  bus->endWrite();
}
